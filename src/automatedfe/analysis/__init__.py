"""Structured run artifact contract.

This package defines the portable artifacts that analysis and tracking will
consume: a schema-versioned run manifest with content fingerprints, stable
expression-derived feature IDs, the run-relative artifact paths, and the
CSV/JSON schemas for inputs, candidates, generations, final archive, archive
snapshots, and status.

Loose legacy CSV/JSON outputs (for example a standalone diagnostics CSV or a
standalone archive snapshot) are never structured runs: integrity evidence
comes from content fingerprints, never from paths alone.
"""

